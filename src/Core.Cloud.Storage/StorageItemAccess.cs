namespace Core.Cloud.Storage
{
    /// <summary>
    /// Defines the access levels for storage items.
    /// </summary>
    public enum StorageItemAccess
    {
        /// <summary>
        /// Grants read access to the storage item.
        /// </summary>
        Read = 1,

        /// <summary>
        /// Grants write access to the storage item.
        /// </summary>
        Write = 2
    }
}
